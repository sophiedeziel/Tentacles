# frozen_string_literal: true

require 'rails_helper'

RSpec.describe Gcode::Slicer do
  describe '.identify' do
    it 'finds PrusaSlicer and its version' do
      expect(described_class.identify(' generated by PrusaSlicer 2.7.4+MacOS-x64 on 2024-05-26 at 02:00:16 UTC'))
        .to eq ['PrusaSlicer', '2.7.4+MacOS-x64']
    end

    it 'finds Cura and its version' do
      expect(described_class.identify('Generated with Cura_SteamEngine 4.11.0')).to eq ['Cura', '4.11.0']
    end

    it 'is nil for another comment' do
      expect(described_class.identify(' generated by OrcaSlicer 2.1.1')).to be_nil
    end
  end
end
